import fs from 'node:fs';
import { defineConfig } from 'astro/config';
import type { AstroUserConfig } from 'astro';
import starlight from '@astrojs/starlight';
import type { StarlightUserConfig } from '@astrojs/starlight/types';
import astroTakumi from 'astro-takumi';
import { makeRender } from '../og/og-render';
import { deriveAccent } from '../og/accent';
import { ROBOTO_BYTES } from '../assets/font-b64';

export interface DocsConfigOptions {
  site: string;
  domain: string;
  title: string;
  projectName?: string;
  description: string;
  logoPath?: string;
  favicon?: string;
  customCss?: string[];
  social?: StarlightUserConfig['social'];
  editLink?: StarlightUserConfig['editLink'];
  locales?: StarlightUserConfig['locales'];
  defaultLocale?: StarlightUserConfig['defaultLocale'];
  plugins?: StarlightUserConfig['plugins'];
  sidebar: StarlightUserConfig['sidebar'];
  routeMiddleware?: string;
  base?: string;
  /** Skip derivation and use this accent verbatim (e.g. rainbow logos where the median lies). */
  accentOverride?: string;
  expressiveCode?: StarlightUserConfig['expressiveCode'];
  extraStarlight?: Partial<StarlightUserConfig>;
  extraIntegrations?: NonNullable<AstroUserConfig['integrations']>;
  extraVite?: Record<string, unknown>;
}

export async function defineDocsConfig(options: DocsConfigOptions): Promise<AstroUserConfig> {
  const {
    site,
    domain,
    title,
    projectName = title,
    description,
    logoPath = './src/assets/logo.png',
    favicon = '/favicon.png',
    customCss = ['./src/styles/custom.css'],
    social = [],
    editLink,
    locales,
    defaultLocale = 'root',
    plugins = [],
    sidebar,
    routeMiddleware = './src/routeData.mjs',
    base,
    accentOverride,
    expressiveCode = { themes: ['github-light', 'github-dark'] },
    extraStarlight = {},
    extraIntegrations = [],
    extraVite = {},
  } = options;

  const accent = accentOverride
    ? { hex: accentOverride, hexA12: accentOverride + '1a' }
    : await deriveAccent(logoPath);

  const logoB64 = fs.readFileSync(logoPath).toString('base64');
  const render = makeRender({
    logoDataUrl: 'data:image/png;base64,' + logoB64,
    accentHex: accent.hex,
    accentHexA12: accent.hexA12,
    domain,
    projectName,
  });

  // Font is embedded as base64 in src/assets/font-b64.ts (generated by prebuild) —
  // avoids fragile relative-path resolution inside tsdown's hashed chunks.

  const starlightOptions: StarlightUserConfig = {
    routeMiddleware,
    expressiveCode,
    title,
    description,
    logo: { src: logoPath },
    favicon,
    customCss,
    social,
    ...(editLink ? { editLink } : {}),
    ...(locales ? { locales } : {}),
    ...(defaultLocale ? { defaultLocale } : {}),
    plugins,
    sidebar,
    ...extraStarlight,
  };

  return defineConfig({
    vite: { ssr: { external: ['jsdom', 'astro-takumi'] }, ...extraVite },
    ...(site ? { site } : {}),
    ...(base ? { base } : {}),
    integrations: [
      starlight(starlightOptions),
      ...extraIntegrations,
      astroTakumi({
        options: {
          domBackend: 'linkedom',
          fonts: [ROBOTO_BYTES],
          width: 1200,
          height: 630,
          format: 'png',
        },
        render,
      } as unknown as Parameters<typeof astroTakumi>[0]),
    ],
  });
}
