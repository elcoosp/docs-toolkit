import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const woff2 = readFileSync('src/assets/roboto-latin-400-normal.woff2');
const b64 = woff2.toString('base64');
const out = 'src/assets/font-b64.ts';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Auto-generated by scripts/prebuild.mjs. Do not edit.
export const ROBOTO_BASE64 = ${JSON.stringify(b64)};
export const ROBOTO_BYTES: Buffer = Buffer.from(ROBOTO_BASE64, 'base64');
`,
);
console.log(`prebuild: wrote ${out} — ${b64.length} b64 chars from ${woff2.length} source bytes`);
